"""Exercise release PR version alignment without Cargo or network access."""

import base64
import copy
import importlib.util
from pathlib import Path
import tempfile
import tomllib
import unittest

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "release_workspace_sync", ROOT / ".github/scripts/sync-release-workspace.py"
)
SYNC = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SYNC)

OLD_VERSION = "0.24.0"
NEW_VERSION = "0.25.0"
REPOSITORY = "syscoin/zksync-os-server"
BRANCH = "release-please--branches--main--components--zksync-os-server"
HEAD = "a" * 40
TREE = "b" * 40
NEW_COMMIT = "c" * 40

MANIFEST = '''# Keep formatting and unrelated dependency requirements intact.
[workspace]
members = ["lib/alpha", "lib/beta"]

[workspace.package]
version = "0.25.0"

[workspace.dependencies]
alpha = { version = "=0.24.0", path = "lib/alpha" }
beta = { path = "lib/beta", version = "=0.24.0", features = ["one"] }
external = { version = "=0.24.0" }

[profile.release]
debug = 1
'''

EXTERNAL_RECORD = '''[[package]]
name = "alpha"
version = "0.24.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "unchanged-external-checksum"

'''

BETA_RECORD = '''[[package]]
name = "beta"
version = "0.24.0"
'''

LOCK = '''# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "alpha"
version = "0.24.0"
dependencies = [
 "beta",
]

''' + EXTERNAL_RECORD + BETA_RECORD


def expected_manifest(version=NEW_VERSION):
    return MANIFEST.replace('version = "=0.24.0", path', f'version = "={version}", path').replace(
        'path = "lib/beta", version = "=0.24.0"',
        f'path = "lib/beta", version = "={version}"',
    )


def expected_lock(version=NEW_VERSION):
    return LOCK.replace(
        'name = "alpha"\nversion = "0.24.0"\ndependencies',
        f'name = "alpha"\nversion = "{version}"\ndependencies',
    ).replace(BETA_RECORD, BETA_RECORD.replace(OLD_VERSION, version))


class AlignVersionsTests(unittest.TestCase):
    def test_only_exact_workspace_pins_and_local_lock_versions_change(self):
        manifest, lock = SYNC.align_versions(
            MANIFEST, LOCK, {"alpha": NEW_VERSION, "beta": NEW_VERSION}
        )
        self.assertEqual(manifest, expected_manifest())
        self.assertEqual(lock, expected_lock())
        self.assertIn(EXTERNAL_RECORD, lock)
        external = [
            package for package in tomllib.loads(lock)["package"] if "source" in package
        ]
        self.assertEqual(external, [package for package in tomllib.loads(LOCK)["package"] if "source" in package])
        self.assertIn('external = { version = "=0.24.0" }', manifest)
        self.assertIn('[workspace.package]\nversion = "0.25.0"', manifest)

    def test_repeated_alignment_is_a_noop(self):
        versions = {"alpha": NEW_VERSION, "beta": NEW_VERSION}
        first = SYNC.align_versions(MANIFEST, LOCK, versions)
        self.assertEqual(SYNC.align_versions(*first, versions), first)

    def test_major_and_prerelease_versions_preserve_exact_requirement(self):
        for version in ("1.0.0", "2.0.0-rc.3"):
            with self.subTest(version=version):
                self.assertEqual(
                    SYNC.align_versions(MANIFEST, LOCK, {"alpha": version, "beta": version}),
                    (expected_manifest(version), expected_lock(version)),
                )

    def test_each_workspace_package_uses_its_own_version(self):
        manifest, lock = SYNC.align_versions(
            MANIFEST, LOCK, {"alpha": "1.0.0", "beta": "2.0.0-rc.1"}
        )
        self.assertIn('alpha = { version = "=1.0.0", path', manifest)
        self.assertIn('path = "lib/beta", version = "=2.0.0-rc.1"', manifest)
        packages = [package for package in tomllib.loads(lock)["package"] if "source" not in package]
        self.assertEqual({package["name"]: package["version"] for package in packages},
                         {"alpha": "1.0.0", "beta": "2.0.0-rc.1"})

    def test_non_exact_or_missing_internal_requirement_fails(self):
        for requirement in ('"0.24.0"', '"^0.24.0"', '">=0.24.0"', '"*"'):
            with self.subTest(requirement=requirement), self.assertRaises(ValueError):
                SYNC.align_versions(
                    MANIFEST.replace('version = "=0.24.0", path', f'version = {requirement}, path'),
                    LOCK,
                    {"alpha": NEW_VERSION, "beta": NEW_VERSION},
                )
        with self.assertRaises(ValueError):
            SYNC.align_versions(
                MANIFEST.replace('version = "=0.24.0", path', 'path'),
                LOCK,
                {"alpha": NEW_VERSION, "beta": NEW_VERSION},
            )

    def test_missing_local_package_cannot_be_satisfied_by_external_record(self):
        lock = LOCK.replace('''[[package]]
name = "alpha"
version = "0.24.0"
dependencies = [
 "beta",
]

''', "")
        with self.assertRaises(ValueError):
            SYNC.align_versions(MANIFEST, lock, {"alpha": NEW_VERSION, "beta": NEW_VERSION})

    def test_duplicate_local_package_fails(self):
        with self.assertRaises(ValueError):
            SYNC.align_versions(
                MANIFEST, LOCK + "\n" + BETA_RECORD, {"alpha": NEW_VERSION, "beta": NEW_VERSION}
            )

    def test_version_qualified_local_dependency_requires_review(self):
        lock = LOCK.replace(' "beta",', ' "beta 0.24.0",')
        with self.assertRaises(ValueError):
            SYNC.align_versions(MANIFEST, lock, {"alpha": NEW_VERSION, "beta": NEW_VERSION})


class FakeGitHub:
    def __init__(self, manifest=MANIFEST, lock=LOCK):
        self.calls = []
        self.manifest = manifest
        self.lock = lock
        self.pull = {
            "state": "open",
            "head": {"sha": HEAD, "ref": BRANCH, "repo": {"full_name": REPOSITORY}},
            "base": {"ref": "main"},
        }
        self.pull_reads = 0
        self.ref_reads = 0
        self.ref_head = HEAD
        self.next_head = None

    def __call__(self, method, endpoint, body=None):
        self.calls.append((method, endpoint, copy.deepcopy(body)))
        prefix = f"repos/{REPOSITORY}/"
        if method == "GET" and endpoint == prefix + "pulls/368":
            self.pull_reads += 1
            return copy.deepcopy(self.pull)
        if method == "GET" and endpoint == prefix + f"git/ref/heads/{BRANCH}":
            self.ref_reads += 1
            head = self.next_head if self.ref_reads > 1 and self.next_head else self.ref_head
            return {"object": {"sha": head}}
        for filename, content in (("Cargo.toml", self.manifest), ("Cargo.lock", self.lock)):
            if method == "GET" and endpoint == prefix + f"contents/{filename}?ref={HEAD}":
                return {"encoding": "base64", "content": base64.b64encode(content.encode()).decode()}
        for filename, content in (("Cargo.toml", expected_manifest()), ("Cargo.lock", expected_lock())):
            if method == "GET" and endpoint == prefix + f"contents/{filename}?ref={'f' * 40}":
                return {"encoding": "base64", "content": base64.b64encode(content.encode()).decode()}
        if method == "GET" and endpoint == prefix + f"git/commits/{HEAD}":
            return {"tree": {"sha": TREE}}
        if method == "POST" and endpoint == prefix + "git/trees":
            return {"sha": "d" * 40}
        if method == "POST" and endpoint == prefix + "git/commits":
            return {"sha": NEW_COMMIT}
        if method == "PATCH" and endpoint == prefix + f"git/refs/heads/{BRANCH}":
            return {"object": {"sha": NEW_COMMIT}}
        raise AssertionError(f"Unexpected GitHub call: {method} {endpoint}")

    def writes(self):
        return [call for call in self.calls if call[0] != "GET"]


class SyncPullRequestTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        (self.root / "Cargo.toml").write_text(MANIFEST.replace(NEW_VERSION, OLD_VERSION))
        for name in ("alpha", "beta"):
            member = self.root / "lib" / name
            member.mkdir(parents=True)
            (member / "Cargo.toml").write_text(f'[package]\nname = "{name}"\nversion.workspace = true\n')

    def test_updates_only_two_cargo_files_and_preserves_generated_pr_history(self):
        api = FakeGitHub()
        self.assertTrue(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        writes = api.writes()
        self.assertEqual([method for method, _, _ in writes], ["POST", "POST", "PATCH"])
        tree = writes[0][2]
        self.assertEqual(tree["base_tree"], TREE)
        self.assertEqual({entry["path"] for entry in tree["tree"]}, {"Cargo.toml", "Cargo.lock"})
        contents = {entry["path"]: entry["content"] for entry in tree["tree"]}
        self.assertEqual(contents, {"Cargo.toml": expected_manifest(), "Cargo.lock": expected_lock()})
        self.assertEqual(writes[1][2]["parents"], [HEAD])
        self.assertEqual(writes[2][2], {"sha": NEW_COMMIT, "force": False})
        self.assertGreaterEqual(api.pull_reads, 2)
        self.assertGreaterEqual(api.ref_reads, 2)

    def test_already_aligned_pr_has_no_write_requests(self):
        api = FakeGitHub(expected_manifest(), expected_lock())
        self.assertFalse(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        self.assertEqual(api.writes(), [])

    def test_stale_pr_head_does_not_hide_unaligned_current_branch(self):
        api = FakeGitHub()
        api.pull["head"]["sha"] = "f" * 40
        self.assertTrue(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        writes = api.writes()
        self.assertEqual(writes[1][2]["parents"], [HEAD])
        self.assertEqual(writes[2][2], {"sha": NEW_COMMIT, "force": False})
        self.assertIn(("GET", f"repos/{REPOSITORY}/contents/Cargo.toml?ref={HEAD}", None), api.calls)
        self.assertIn(("GET", f"repos/{REPOSITORY}/contents/Cargo.lock?ref={HEAD}", None), api.calls)

    def test_stale_pr_head_with_aligned_current_branch_is_a_noop(self):
        api = FakeGitHub(expected_manifest(), expected_lock())
        api.pull["head"]["sha"] = "f" * 40
        self.assertFalse(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        self.assertEqual(api.writes(), [])
        self.assertGreaterEqual(api.ref_reads, 1)

    def test_rejects_foreign_repo_wrong_base_head_and_closed_pr(self):
        mutations = (
            ("foreign repository", lambda pull: pull["head"]["repo"].update(full_name="other/fork")),
            ("wrong base", lambda pull: pull["base"].update(ref="develop")),
            ("unrelated branch", lambda pull: pull["head"].update(ref="codex/other-change")),
            ("closed PR", lambda pull: pull.update(state="closed")),
        )
        for name, mutate in mutations:
            with self.subTest(name=name):
                api = FakeGitHub()
                mutate(api.pull)
                with self.assertRaises(ValueError):
                    SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api)
                self.assertEqual(api.writes(), [])

    def test_concurrent_head_advance_does_not_update_branch(self):
        api = FakeGitHub()
        api.next_head = "e" * 40
        with self.assertRaises(ValueError):
            SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api)
        self.assertGreaterEqual(api.ref_reads, 2)
        self.assertFalse(any(method == "PATCH" for method, _, _ in api.calls))

    def test_invalid_remote_pin_fails_before_any_write(self):
        api = FakeGitHub(manifest=MANIFEST.replace('version = "=0.24.0", path', 'version = "^0.24.0", path'))
        with self.assertRaises(ValueError):
            SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api)
        self.assertEqual(api.writes(), [])

    def test_changed_workspace_membership_fails_before_any_write(self):
        api = FakeGitHub(manifest=MANIFEST.replace('"lib/alpha", "lib/beta"', '"lib/alpha"'))
        with self.assertRaises(ValueError):
            SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api)
        self.assertEqual(api.writes(), [])

    def test_explicit_member_version_does_not_inherit_release_version(self):
        (self.root / "lib/beta/Cargo.toml").write_text('[package]\nname = "beta"\nversion = "7.0.0"\n')
        api = FakeGitHub()
        self.assertTrue(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        contents = {entry["path"]: entry["content"] for entry in api.writes()[0][2]["tree"]}
        self.assertIn('path = "lib/beta", version = "=7.0.0"', contents["Cargo.toml"])
        self.assertIn('name = "beta"\nversion = "7.0.0"', contents["Cargo.lock"])

    def test_local_path_dependency_omitted_from_explicit_members_is_aligned(self):
        manifest = MANIFEST.replace('"lib/alpha", "lib/beta"', '"lib/alpha"')
        (self.root / "Cargo.toml").write_text(manifest.replace(NEW_VERSION, OLD_VERSION))
        api = FakeGitHub(manifest=manifest)
        self.assertTrue(SYNC.sync_pull_request(REPOSITORY, 368, root=self.root, api=api))
        contents = {entry["path"]: entry["content"] for entry in api.writes()[0][2]["tree"]}
        self.assertEqual(contents["Cargo.toml"], expected_manifest().replace('"lib/alpha", "lib/beta"', '"lib/alpha"'))
        self.assertEqual(contents["Cargo.lock"], expected_lock())


if __name__ == "__main__":
    unittest.main()
